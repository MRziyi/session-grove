test('project collections contain standalone items and trees; logical commits alone do not make a tree', t => {
    const { store, cwd } = setup(t), p = store.project('Mixed'), b = store.branch(p.id, 'Notes', 'codex', codexSample(cwd, [['One', 'Done'], ['Two', 'Done']]));
    let d = store.detail(b.id);
    store.commitPending(b.id, { name: 'One', end: d.checkpoints[0].end, revisionId: d.head, expectedStart: 0 });
    d = store.detail(b.id);
    store.commitPending(b.id, { name: 'Two', end: d.checkpoints[1].end, revisionId: d.head, expectedStart: d.pending.start });
    assert.equal(store.forest(p.id)[0].kind, 'session');
    store.fork(b.id, { name: 'Explore', end: d.checkpoints[0].end });
    store.branch(p.id, 'Loose notes', 'codex');
    assert.deepEqual(store.forest(p.id).map(i => i.kind).sort(), ['session', 'tree']);
});
test('cloud exports only filed projects, including logical nodes; device Active never transfers', t => {
    const a = setup(t), b = setup(t), p = a.store.project('Cloud');
    const local = a.store.branch(null, 'Private local', 'codex', codexSample(a.cwd, [['Private local text', 'Not for cloud']]));
    const filed = a.store.branch(p.id, 'Filed', 'codex', codexSample(a.cwd, [['File me', 'Okay']]));
    const d = a.store.detail(filed.id);
    a.store.commitPending(filed.id, { name: 'Milestone', end: d.checkpoints[0].end, revisionId: d.head, expectedStart: 0 });
    const graph = a.store.exportGraph();
    assert.equal(graph.branches.length, 1);
    assert.equal(graph.nodes.length, 1);
    const bodies = graph.revisions.flatMap(r => r.refs).map(h => a.store.db.prepare('SELECT body FROM objects WHERE hash=?').get(h).body).join('');
    assert.ok(!bodies.includes('Private local text'));
    copy(a.store, b.store);
    assert.equal(b.store.detail(filed.id).nodes[0].name, 'Milestone');
    assert.equal(b.store.instances().length, 0);
    a.store.edit(filed.id, { name: 'Renamed' });
    copy(a.store, b.store);
    assert.equal(b.store.get('branch', filed.id).name, 'Renamed');
    assert.equal(b.store.local('conflicts').length, 0);
    a.store.moveTree(local.id, p.id, 'Misc');
    copy(a.store, b.store);
    assert.equal(b.store.forest(p.id).length, 2);
});
test('automatic upload queue survives lock and failures and only runs after an organization trigger', async t => {
    const { store, cwd } = setup(t), p = store.project('Queued'), b = store.branch(p.id, 'Main', 'codex', codexSample(cwd, [['Context', 'Ready']]));
    let attempts = 0;
    const auto = new AutoSync(store, () => ({ url: 'https://example.com/dav' }), async () => { attempts++; throw new Error('offline'); });
    t.after(() => auto.close());
    auto.schedule([b.id]); await auto.flush(); assert.equal(attempts, 0);
    auto.unlock('my-test-passphrase'); await assert.rejects(auto.flush(), /offline/);
    assert.equal(auto.status().phase, 'retrying'); assert.deepEqual(store.local('uploadQueue'), [b.id]);
    auto.lock(); assert.equal(auto.status().phase, 'locked');
});
test('concurrent logical organization preserves both partitions without displaying overlapping nodes', t => {
    const a = setup(t), b = setup(t), p = a.store.project('Shared');
    const branch = a.store.branch(p.id, 'Main', 'codex', codexSample(a.cwd, [['One', 'A'], ['Two', 'B']]));
    copy(a.store, b.store);
    const d = a.store.detail(branch.id);
    a.store.commitPending(branch.id, { name: 'First stage', end: d.checkpoints[0].end, revisionId: d.head, expectedStart: 0 });
    b.store.commitPending(branch.id, { name: 'One combined stage', end: d.checkpoints[1].end, revisionId: d.head, expectedStart: 0 });
    const merged = copy(a.store, b.store);
    assert.equal(merged.conflicts, 1);
    assert.equal(b.store.local('conflicts')[0].kind, 'organization');
    assert.equal(b.store.all('node').length, 2);
    assert.equal(b.store.detail(branch.id).nodes.length, 1);
    assert.equal(b.store.detail(branch.id).nodes[0].name, 'One combined stage');
    assert.equal(b.store.detail(branch.id).pending.count, 0);
});
test('sequential logical commits fast-forward across devices with the remaining Pending intact', t => {
    const a = setup(t), b = setup(t), p = a.store.project('Shared');
    const branch = a.store.branch(p.id, 'Main', 'codex', codexSample(a.cwd, [['One', 'A'], ['Two', 'B']]));
    let d = a.store.detail(branch.id);
    a.store.commitPending(branch.id, { name: 'Stage one', end: d.checkpoints[0].end, revisionId: d.head, expectedStart: 0 });
    copy(a.store, b.store);
    assert.equal(b.store.detail(branch.id).pending.count, 2);
    d = b.store.detail(branch.id);
    b.store.commitPending(branch.id, { name: 'Stage two', end: d.checkpoints[1].end, revisionId: d.head, expectedStart: d.pending.start });
    assert.equal(copy(b.store, a.store).conflicts, 0);
    assert.deepEqual(a.store.detail(branch.id).nodes.map(n => n.name), ['Stage one', 'Stage two']);
    assert.equal(a.store.detail(branch.id).pending.count, 0);
});
