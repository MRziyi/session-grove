function setup(t) {
    const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'grove-organize-')));
    const store = new Store(path.join(root, 'library')), cwd = path.join(root, 'work');
    const roots = { codex: path.join(root, 'codex'), claude: path.join(root, 'claude') };
    fs.mkdirSync(cwd);
    fs.mkdirSync(path.join(roots.codex, 'sessions'), { recursive: true });
    const native = new Native(store, { roots, guard: () => { } });
    t.after(() => { store.close(); fs.rmSync(root, { recursive: true, force: true }); });
    return { root, store, native, roots, cwd };
}
const append = pairs => pairs.flatMap(([u, a]) => codexTurn(u, a)).map(v => JSON.stringify(v) + '\n').join('');
const copy = (from, to) => to.merge(from.exportGraph(), Object.fromEntries(from.db.prepare('SELECT * FROM objects').all().map(o => [o.hash, o.body])));
test('20 new messages remain Pending, then commit as two named 10-message nodes without rewriting native data', t => {
    const { store, native, roots, cwd } = setup(t), project = store.project('Chrono');
    const raw = codexSample(cwd, [['Context', 'Ready']]);
    const branch = store.branch(project.id, 'Main', 'codex', raw);
    let detail = store.detail(branch.id);
    store.commitPending(branch.id, { name: 'Research context', end: detail.pending.checkpoints[0].end, revisionId: branch.head, expectedStart: 0 });
    native.setActive(branch.id, cwd, true);
    native.apply();
    const file = store.instances()[0].file;
    fs.appendFileSync(file, append(Array.from({ length: 10 }, (_, i) => [`Question ${i}`, `Answer ${i}`])));
    const nativeBefore = fs.readFileSync(file, 'utf8');
    native.refreshLocal();
    detail = store.detail(branch.id);
    assert.equal(detail.pending.count, 20);
    assert.equal(detail.nodes.length, 1);
    const boundary = detail.pending.checkpoints.find(c => c.messages === 10);
    const first = store.commitPending(branch.id, { name: 'Write Intro', end: boundary.end, revisionId: detail.head, expectedStart: detail.pending.start });
    detail = store.detail(branch.id);
    assert.equal(detail.pending.count, 10);
    assert.equal(detail.nodes.length, 2);
    const second = store.commitPending(branch.id, { name: 'Design experiments', end: detail.pending.checkpoints.at(-1).end, revisionId: detail.head, expectedStart: detail.pending.start });
    assert.equal(first.end, second.start);
    assert.equal(store.detail(branch.id).pending.count, 0);
    assert.equal(fs.readFileSync(file, 'utf8'), nativeBefore);
    native.refreshLocal();
    assert.equal(store.detail(branch.id).pending.count, 0);
    fs.appendFileSync(file, append([['One more task', 'Done']]));
    native.refreshLocal();
    assert.equal(store.detail(branch.id).pending.count, 2);
    assert.equal(store.detail(branch.id).nodes.length, 3);
});
test('stale or duplicate Pending commits fail without dropping records', t => {
    const { store, cwd } = setup(t), b = store.branch(null, 'Local', 'codex', codexSample(cwd, [['A', 'B'], ['C', 'D']]));
    const d = store.detail(b.id), options = { name: 'Part 1', end: d.checkpoints[0].end, revisionId: d.head, expectedStart: 0 };
    store.commitPending(b.id, options);
    assert.throws(() => store.commitPending(b.id, options), /already organized/);
    store.ingest(b.id, store.raw(d.head) + append([['E', 'F']]), d.head, {});
    assert.throws(() => store.commitPending(b.id, { ...options, expectedStart: options.end }), /Pending changed/);
    assert.equal(store.detail(b.id).pending.count, 4);
});
test('native local discovery preserves Active and groups three exact-prefix forks into one tree', t => {
    const { store, native, roots, cwd } = setup(t);
    for (let i = 0; i < 3; i++)
        fs.writeFileSync(path.join(roots.codex, 'sessions', `session-${i}.jsonl`), codexSample(cwd, [['Research', 'Context'], ['Shared constraints', 'Understood'], [`Direction ${i}`, `Outcome ${i}`]]));
    const result = native.refreshLocal();
    assert.equal(result.discovered, 3);
    const items = store.forest('local');
    assert.equal(items.length, 1);
    assert.equal(items[0].kind, 'tree');
    assert.equal(items[0].branchIds.length, 4);
    assert.equal(items[0].activeCount, 3);
    assert.equal(native.plan().operations.length, 0);
    native.refreshLocal();
    assert.equal(store.all('branch').length, 4);
    const p = store.project('Chrono');
    store.moveTree(items[0].id, p.id, 'Research');
    const projectItems = store.forest(p.id);
    assert.equal(projectItems.length, 1);
    assert.equal(projectItems[0].group, 'Research');
    assert.equal(projectItems[0].branchIds.length, 4);
    assert.equal(store.forest('local')[0].id, items[0].id);
});
